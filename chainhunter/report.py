# ---------- ATT&CK Navigator layer ----------

def navigator_layer(chains: list[Chain], name: str = "ChainHunter detections") -> str:
    counts: dict[str, int] = {}
    for c in chains:
        for d in c.detections:
            for t in d.rule.attack_ids:
                counts[t] = counts.get(t, 0) + 1
    return json.dumps({
        "name": name, "versions": {"layer": "4.5", "navigator": "4.9.1", "attack": "15"},
        "domain": "enterprise-attack",
        "techniques": [{"techniqueID": t, "score": n, "comment": f"{n} detection(s)"} for t, n in sorted(counts.items())],
        "gradient": {"colors": ["#fde0dd", "#b4232a"], "minValue": 0, "maxValue": max(counts.values(), default=1)},
    }, indent=2)


def coverage_layer(rules: list[Rule]) -> str:
    techs = sorted({t for r in rules for t in r.attack_ids})
    return json.dumps({
        "name": "ChainHunter rule coverage", "versions": {"layer": "4.5", "navigator": "4.9.1", "attack": "15"},
        "domain": "enterprise-attack",
        "techniques": [{"techniqueID": t, "score": 1, "color": "#1f5fa8",
                        "comment": ", ".join(r.id for r in rules if t in r.attack_ids)} for t in techs],
    }, indent=2)


