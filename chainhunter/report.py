def _ts(dt) -> str:
    return dt.strftime("%Y-%m-%d %H:%M:%S UTC")


def _ioc_type(value: str) -> str:
    try:
        ipaddress.ip_address(value)
        return "IP Address"
    except ValueError:
        pass
    if "\\" in value or value.lower().endswith(".exe"):
        return "Process"
    if value.upper().startswith("CN="):
        return "Directory Object"
    return "Workstation/Domain"


def _queries(d: Detection, registry: dict[str, Rule]) -> dict[str, str]:
    return d.extra.get("queries") or queries_for(d.rule, registry)


def _kind_label(d: Detection) -> str:
    return {"sequence": " [SEQUENCE]", "anomaly": " [ANOMALY]"}.get(d.rule.kind, "")


# ---------- Markdown (CDSA commercial format) ----------

def markdown_report(chains: list[Chain], registry: dict[str, Rule], title: str = "Security Incident Report") -> str:
    out = [f"# {title}", f"_Generated by ChainHunter on {_ts(datetime.now(timezone.utc))}_", ""]
    if not chains:
        return "\n".join(out + ["No detections."])

    for n, c in enumerate(chains, 1):
        ents = c.entities
        seqs = [d for d in c.detections if d.rule.kind == "sequence"]
        out += [
            f"## Incident {n} — Severity: {c.severity} (score {c.score})",
            f"**Confidence:** {c.confidence}  ",
            f"**Window:** {_ts(c.start)} → {_ts(c.end)}  ",
            f"**ATT&CK:** {', '.join(c.techniques)}",
            "",
            "### Executive Summary",
            "#### Incident Overview",
            f"Between {_ts(c.start)} and {_ts(c.end)}, ChainHunter correlated {len(c.detections)} detections "
            f"across {len(ents['hosts'])} host(s) and {len(ents['accounts'])} account(s) into one attack chain "
            f"progressing through **{' → '.join(c.phases)}**.",
        ]
        if seqs:
            out.append(f"{len(seqs)} multi-stage sequence rule(s) confirmed ordered attacker activity, "
                       f"raising confidence that this is a single coordinated intrusion rather than unrelated alerts.")
        groups = group_alerts(c)
        story = [g for g in groups if g.level in ALERT_LEVELS] or groups
        context = [g for g in groups if g not in story]
        out += ["", "#### Key Findings"]
        for g in story:
            d = g.detections[0]
            out.append(f"- {_ts(g.first)} — **{g.rule.title}**{_kind_label(d)} on `{short_host(g.host) or 'n/a'}`"
                       f"{f' (×{g.count})' if g.count > 1 else ''} — {g.level}")
        flagged = [r for r in c.risk if r.flagged]
        out += ["", "#### Immediate Actions"]
        for r in flagged:
            action = {"Account": "Disable / reset credentials (twice for krbtgt if replication abuse is confirmed)",
                      "Source": "Block at perimeter/EDR and hunt for further activity",
                      "Host": "Isolate and acquire memory + disk for forensics"}[r.kind]
            out.append(f"- {r.kind} `{r.value}` — {action}.")
        out += ["- _Analyst to confirm and extend._", "", "#### Stakeholder Impact",
                "- _Analyst to complete: affected business services, data, and users._", ""]

        out += ["### Risk-Based Alerting — Entity Risk", "",
                "| Entity | Type | Risk | Techniques | Phases | Flagged |", "|---|---|---|---|---|---|"]
        for r in c.risk[:12]:
            out.append(f"| `{r.value}` | {r.kind} | {r.score} | {', '.join(sorted(r.techniques))} | "
                       f"{len(r.phases)} | {'**YES**' if r.flagged else 'no'} |")

        out += ["", "### Technical Analysis", "#### Affected Systems & Data",
                f"- Hosts: {', '.join(sorted(ents['hosts'])) or 'n/a'}",
                f"- Accounts: {', '.join(sorted(ents['accounts'])) or 'n/a'}"]
        if ents.get("targeted"):
            out.append(f"- Targeted accounts: {', '.join(sorted(ents['targeted']))}")
        out += ["", "#### Evidence Sources & Analysis", ""]

        for step, g in enumerate(story, 1):
            d = g.detections[0]
            out += [f"##### Step {step} — {d.rule.title}{_kind_label(d)}", f"**Objective:** {d.rule.description}", ""]
            if d.rule.kind == "sequence":
                out.append("**Sequence stages:**")
                for sid, sd in d.extra["steps"]:
                    out.append(f"1. `{sid}` — {_ts(sd.time)} · {sd.rule.title} · actor `{sd.actor or 'n/a'}` on `{sd.host or 'n/a'}`")
                out.append("")
            for lang, q in _queries(d, registry).items():
                out += [f"```{lang}", q, "```"]
            detail = ""
            if d.rule.kind == "anomaly":
                detail = " " + ", ".join(f"{k}={v}" for k, v in d.extra.items() if k != "queries")
            out += ["", f"_Figure {n}.{step} - {d.rule.title} evidence (attach screenshot)_", "",
                    f"**Finding:** {g.count} detection(s), {len(g.events)} event(s) from {_ts(g.first)} to {_ts(g.last)} "
                    f"on `{g.host or 'n/a'}`; actor(s) `{', '.join(show(a) for a in g.actors[:5]) or 'n/a'}`.{detail}", "",
                    f"**Kill Chain Phase:** {d.rule.meta.get('kill_chain', 'Unknown')} · "
                    f"**MITRE ATT&CK:** {', '.join(d.rule.attack_ids) or 'n/a'}", ""]
        if context:
            out += ["#### Low / informational context", "", "| First seen | Alert | Host | Count |", "|---|---|---|---|"]
            out += [f"| {_ts(g.first)} | {g.rule.title} | {short_host(g.host)} | {g.count} |" for g in context]
            out.append("")

        out += ["### Indicators of Compromise", "", "| Type | Value | Context |", "|---|---|---|"]
        out += [f"| {_ioc_type(s)} | `{s}` | Origin of malicious activity |" for s in sorted(ents["sources"])]
        out += [f"| Account | `{a}` | Used during intrusion |" for a in sorted(ents["accounts"])]
        out += [f"| Host | `{h}` | Affected system |" for h in sorted(ents["hosts"])]
        out += ["", "### Appendix: Technical Timeline", "",
                "| First seen (UTC) | Host | Alert | Count | Phase | ATT&CK |", "|---|---|---|---|---|---|"]
        for g in story:
            out.append(f"| {_ts(g.first)} | {short_host(g.host)} | {g.rule.title}{_kind_label(g.detections[0])} | "
                       f"{g.count} | {g.rule.meta.get('kill_chain', '')} | {', '.join(g.rule.attack_ids)} |")
        out.append("")
    return "\n".join(out)


