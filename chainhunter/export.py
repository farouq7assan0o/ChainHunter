"""Hand incidents to the tools a SOC already runs: TheHive 5 alerts, MISP events, STIX 2.1 bundles.

    chainhunter hunt logs/ -r rules --export thehive,misp,stix          # write files to the output folder
    chainhunter hunt logs/ -r rules --push-thehive https://thehive:9000 # also POST alerts (key: THEHIVE_API_KEY)
    chainhunter hunt logs/ -r rules --push-misp https://misp.local      # also POST events (key: MISP_API_KEY)

What goes across:
  * title, severity, time window, kill chain, a Markdown summary of the medium+ alert groups
  * observables: IP addresses, hostnames, accounts and process/file names from the incident's entities
    (cloud service names like "Entra ID" are not hosts and are left out)
  * ATT&CK techniques: TheHive procedures (patternId), MISP tags, STIX attack-pattern objects
Files are always written; pushing to a server only happens with an explicit --push-* flag. API keys come from
environment variables, never the command line (so they don't end up in shell history or process lists).
IDs are deterministic (same incident -> same sourceRef / STIX id), so re-exporting doesn't create duplicates.
"""
from __future__ import annotations

import hashlib
import ipaddress
import json
import os
import urllib.error
import urllib.request
import uuid
from datetime import datetime, timezone

from .correlate import ALERT_LEVELS, Chain
from .story import group_alerts, short_host, show

SEVERITY_THEHIVE = {"Low": 1, "Medium": 2, "High": 3, "Critical": 4}
THREAT_LEVEL_MISP = {"Critical": 1, "High": 1, "Medium": 2, "Low": 3}   # MISP: 1 high, 2 medium, 3 low
STIX_NS = uuid.UUID("6f1c2f2e-6a2e-4e7a-9c1a-5b3c6f0d9a11")            # namespace for deterministic STIX ids
TLP_AMBER = 2


def incident_ref(c: Chain) -> str:
    """Stable id for an incident: same first detection + window -> same id across re-runs."""
    first = c.detections[0]
    raw = f"{first.rule.id}|{first.time.isoformat()}|{first.host}|{c.start.isoformat()}"
    return "chainhunter-" + hashlib.sha256(raw.encode()).hexdigest()[:16]


def _is_ip(v: str) -> bool:
    try:
        ipaddress.ip_address(v)
        return True
    except ValueError:
        return False


def observables(c: Chain) -> list[dict]:
    """Entities as typed observables: {'type': ip|hostname|account|filename, 'value', 'tags'}."""
    out, seen = [], set()

    def add(t, v, tag):
        v = show(str(v)).strip()
        if v and (t, v.lower()) not in seen:
            seen.add((t, v.lower()))
            out.append({"type": t, "value": v, "tags": [tag]})

    for s in c.entities.get("sources", ()):
        if _is_ip(s):
            add("ip", s, "source")
        elif "\\" in s or s.lower().endswith(".exe"):
            add("filename", s.rsplit("\\", 1)[-1], "process")
    for h in c.entities.get("hosts", ()):
        if " " not in h:  # "Entra ID", "Microsoft 365 Defender" are services, not hosts
            add("hostname", h, "affected-host")
    for a in c.entities.get("accounts", ()):
        add("account", a, "account")
    for t in c.entities.get("targeted", ()):
        add("account", t, "targeted")
    return out


def summary_markdown(c: Chain, max_groups: int = 25) -> str:
    groups = [g for g in group_alerts(c) if g.level in ALERT_LEVELS] or group_alerts(c)
    lines = [f"**Severity:** {c.severity} (score {c.score}) · **Confidence:** {c.confidence}",
             f"**Window:** {c.start:%Y-%m-%d %H:%M:%S} → {c.end:%Y-%m-%d %H:%M:%S} UTC",
             f"**Kill chain:** {' → '.join(c.phases)}",
             f"**ATT&CK:** {', '.join(c.techniques)}", "",
             "| First seen (UTC) | Severity | Alert | Host | Count |", "|---|---|---|---|---|"]
    for g in groups[:max_groups]:
        lines.append(f"| {g.first:%H:%M:%S} | {g.level} | {g.rule.title} | {short_host(g.host)} | {g.count} |")
    if len(groups) > max_groups:
        lines.append(f"\n_{len(groups) - max_groups} more alert groups in the ChainHunter report._")
    flagged = [r for r in c.risk if r.flagged]
    if flagged:
        lines += ["", "**High-risk entities:** " + ", ".join(f"`{show(r.value)}` ({r.kind}, risk {r.score})" for r in flagged[:10])]
    lines += ["", "_Generated by ChainHunter._"]
    return "\n".join(lines)


def _ms(dt: datetime) -> int:
    return int(dt.timestamp() * 1000)


# ---------- TheHive 5 ----------

THEHIVE_TYPES = {"ip": "ip", "hostname": "hostname", "filename": "filename", "account": "other"}


def thehive_alert(c: Chain, title: str = "ChainHunter incident") -> dict:
    """Body for POST /api/v1/alert (TheHive 5)."""
    first_by_tech: dict[str, datetime] = {}
    for d in c.detections:
        for t in d.rule.attack_ids:
            first_by_tech.setdefault(t, d.time)
    return {
        "type": "chainhunter",
        "source": "ChainHunter",
        "sourceRef": incident_ref(c),
        "title": f"{title}: {c.severity} - {' -> '.join(c.phases[:4])}",
        "description": summary_markdown(c),
        "severity": SEVERITY_THEHIVE.get(c.severity, 2),
        "date": _ms(c.start),
        "tlp": TLP_AMBER,
        "pap": TLP_AMBER,
        "tags": ["chainhunter"] + [f"attack:{t}" for t in c.techniques][:30],
        "observables": [{"dataType": THEHIVE_TYPES[o["type"]], "data": o["value"],
                         "tags": o["tags"] + ([f"type:{o['type']}"] if o["type"] == "account" else [])}
                        for o in observables(c)],
        "procedures": [{"patternId": t, "occurDate": _ms(when), "description": "Detected by ChainHunter"}
                       for t, when in sorted(first_by_tech.items())],
    }


# ---------- MISP ----------

MISP_TYPES = {"ip": ("ip-src", "Network activity"), "hostname": ("hostname", "Network activity"),
              "filename": ("filename", "Payload delivery"), "account": ("target-user", "Targeting data")}


def misp_event(c: Chain, title: str = "ChainHunter incident") -> dict:
    """Body for POST /events (MISP), in MISP's JSON event format."""
    attrs = []
    for o in observables(c):
        t, cat = MISP_TYPES[o["type"]]
        attrs.append({"type": t, "category": cat, "value": o["value"], "to_ids": False,
                      "comment": ", ".join(o["tags"])})
    attrs.append({"type": "text", "category": "Other", "value": summary_markdown(c), "to_ids": False,
                  "comment": "ChainHunter incident summary"})
    return {"Event": {
        "info": f"{title}: {c.severity} - {' -> '.join(c.phases[:4])}",
        "date": c.start.strftime("%Y-%m-%d"),
        "threat_level_id": str(THREAT_LEVEL_MISP.get(c.severity, 2)),
        "analysis": "1",            # 1 = ongoing
        "distribution": "0",        # 0 = your organisation only
        "uuid": str(uuid.uuid5(STIX_NS, incident_ref(c))),
        "Tag": [{"name": "tlp:amber"}, {"name": "chainhunter"}] + [{"name": f"mitre-attack:{t}"} for t in c.techniques],
        "Attribute": attrs,
    }}


# ---------- STIX 2.1 ----------

def _sid(kind: str, key: str) -> str:
    return f"{kind}--{uuid.uuid5(STIX_NS, kind + '|' + key)}"


def stix_bundle(chains: list[Chain], title: str = "ChainHunter incident") -> dict:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
    ident = {"type": "identity", "spec_version": "2.1", "id": _sid("identity", "chainhunter"),
             "created": "2026-01-01T00:00:00.000Z", "modified": "2026-01-01T00:00:00.000Z",
             "name": "ChainHunter", "identity_class": "system"}
    objects, seen = [ident], {ident["id"]}

    def push(obj):
        if obj["id"] not in seen:
            seen.add(obj["id"])
            objects.append(obj)
        return obj["id"]

    for c in chains:
        refs = []
        for t in c.techniques:
            refs.append(push({"type": "attack-pattern", "spec_version": "2.1", "id": _sid("attack-pattern", t),
                              "created": now, "modified": now, "name": t, "created_by_ref": ident["id"],
                              "external_references": [{"source_name": "mitre-attack", "external_id": t,
                                                       "url": f"https://attack.mitre.org/techniques/{t.replace('.', '/')}/"}]}))
        for o in observables(c):
            if o["type"] == "ip":
                kind = "ipv6-addr" if ":" in o["value"] else "ipv4-addr"
                refs.append(push({"type": kind, "spec_version": "2.1", "id": _sid(kind, o["value"]), "value": o["value"]}))
            elif o["type"] == "account":
                refs.append(push({"type": "user-account", "spec_version": "2.1", "id": _sid("user-account", o["value"].lower()),
                                  "account_login": o["value"]}))
            elif o["type"] == "filename":
                refs.append(push({"type": "file", "spec_version": "2.1", "id": _sid("file", o["value"].lower()), "name": o["value"]}))
        hosts = [o["value"] for o in observables(c) if o["type"] == "hostname"]
        note = push({"type": "note", "spec_version": "2.1", "id": _sid("note", incident_ref(c)), "created": now,
                     "modified": now, "created_by_ref": ident["id"], "abstract": "ChainHunter incident summary",
                     "content": summary_markdown(c) + ("\n\nAffected hosts: " + ", ".join(hosts) if hosts else ""),
                     "object_refs": refs or [ident["id"]]})
        push({"type": "report", "spec_version": "2.1", "id": _sid("report", incident_ref(c)), "created": now,
              "modified": now, "created_by_ref": ident["id"], "name": f"{title}: {c.severity} - {' -> '.join(c.phases[:4])}",
              "description": f"{len(c.detections)} correlated detections, kill chain {' -> '.join(c.phases)}",
              "published": c.start.strftime("%Y-%m-%dT%H:%M:%S.000Z"), "report_types": ["attack-pattern", "observed-data"],
              "labels": [f"severity:{c.severity.lower()}"], "object_refs": refs + [note]})
    return {"type": "bundle", "id": f"bundle--{uuid.uuid4()}", "objects": objects}


# ---------- push ----------

class PushError(RuntimeError):
    pass


def _post(url: str, body: dict, headers: dict, timeout: int = 30) -> dict:
    req = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST",
                                 headers={"Content-Type": "application/json", "Accept": "application/json", **headers})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            text = r.read().decode() or "{}"
            return json.loads(text)
    except urllib.error.HTTPError as e:
        detail = e.read().decode(errors="replace")[:300]
        raise PushError(f"{url} -> HTTP {e.code}: {detail}") from e
    except urllib.error.URLError as e:
        raise PushError(f"{url} unreachable: {e.reason}") from e


def push_thehive(base: str, alerts: list[dict], key: str | None = None) -> list[str]:
    key = key or os.environ.get("THEHIVE_API_KEY")
    if not key:
        raise PushError("set THEHIVE_API_KEY in the environment (never pass keys on the command line)")
    out = []
    for a in alerts:
        try:
            res = _post(base.rstrip("/") + "/api/v1/alert", a, {"Authorization": f"Bearer {key}"})
            out.append(f"created {res.get('_id', '?')} ({a['sourceRef']})")
        except PushError as e:
            if "HTTP 400" in str(e) and "exist" in str(e).lower():  # same sourceRef already imported
                out.append(f"exists ({a['sourceRef']})")
            else:
                raise
    return out


def push_misp(base: str, events: list[dict], key: str | None = None) -> list[str]:
    key = key or os.environ.get("MISP_API_KEY")
    if not key:
        raise PushError("set MISP_API_KEY in the environment (never pass keys on the command line)")
    out = []
    for ev in events:
        res = _post(base.rstrip("/") + "/events", ev, {"Authorization": key})
        out.append(f"created event {res.get('Event', {}).get('id', '?')} ({ev['Event']['uuid']})")
    return out
